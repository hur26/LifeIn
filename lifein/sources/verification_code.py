"""验证码识别 —— 铁律 11 的服务端那一道。

[R10](../../docs/05-risks.md#r10--手机端采集器的越权读取) 把它的分量说得很清楚:
**账单泄露是隐私损失,验证码泄露是资金损失**,严重程度差一个量级。
所以过滤要做两遍:手机端转发前一遍,服务端入库前再一遍。

**两道必须独立。** 07 §4 原本把这份正则写成"配置项",现在改成两份代码常量
(这里,以及安卓端的 `VerificationCode.kt`)—— 两端共用一份配置的那一刻,
"双重丢弃"就退化成了一道,而手机端那道的全部价值正在于它和这一道
**独立失效**。代价是改一次要动两处并重新发版,这个代价是有意付的。

正则本身允许调整,但**只能放宽不能收窄** —— 收窄意味着更多验证码流进系统。

命中的消息**整条丢弃**:不入库、不进队列、日志里也只记条数不记原文。
记一条"丢弃了这个:【某某】您的验证码是 123456"的日志,等于把刚拦下来的东西
写进了另一个更少人看管的地方。
"""

from __future__ import annotations

import re

PATTERN = (
    r"验证码|校验码|动态密码|verification code|"
    r"\b\d{4,8}\b\s*(?:为|是)?\s*(?:您的)?(?:验证码|校验码)"
)
"""与 07 §4 逐字一致。改它要同时改文档和安卓端那份。"""

_MATCHER = re.compile(PATTERN, re.IGNORECASE)


def looks_like_verification_code(*parts: str | None) -> bool:
    """标题、正文里任何一处命中就算命中。

    分开传而不是让调用方拼起来:拼接会在两段之间造出原本不存在的相邻关系,
    "您的" + "验证码" 分属标题和正文时本来就该算命中,而
    "…动态" + "密码保护…" 拼起来才像命中的那种,不该算。
    """
    return any(part and _MATCHER.search(part) for part in parts)
