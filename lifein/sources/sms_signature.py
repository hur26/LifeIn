"""短信签名 —— 白名单识别银行的那个标识符(ADR-034)。

国内的商业短信在正文开头带一个 `【机构名】`。**它由发信方写进内容**,
所以不受两件事影响,而那两件事正是号码匹配失效的原因:

- 厂商把发件号码换成显示名(通知标题变成"招商银行")
- 银行走 SP 网关下发(真实号码是 `10693495555`,`95555` 是**子串不是前缀**)

2026-09-11 的三条真实短信里,签名是唯一三条都指向正确机构的信号:

    sender='招商银行'       签名='招商银行'
    sender='游戏中心'       签名='游戏中心'
    sender='10693495555'    签名='招商银行'

**这份提取和安卓端的 `SmsSignature.kt` 各写各的,不共用配置。**
理由和验证码那两份一样([铁律 11](../../AGENTS.md)):两端各自从自己手里那份
正文里抠一次,才是两道独立的过滤。传一个"设备算好的签名"上来,服务端这一道
就退化成"信任设备算的"。

**只认开头,不认结尾。** 有些营销短信把签名放在末尾,但 2026-09 手上的真实
样本里三条都在开头 —— 见到结尾的那天再扩,不要现在就为没见过的形状写代码
(ADR-034 的重评触发条件里写着这一条)。

**签名可以伪造。** 谁都能发一条以 `【招商银行】` 开头的短信。白名单是范围
控制不是真伪控制(进来的一律 `trust=external`),真伪归四层防误判管 ——
但那是一个新的注入面,ADR-034 里写着它和 03 退出条件的关系。
"""

from __future__ import annotations

import re

PATTERN = r"^[\s]*[【\[]([^】\]]{1,20})[】\]]"
"""正文开头的 `【…】`。中英文方括号都认 —— 有些网关会把它转成 ASCII 的。

长度上限 20:签名是机构名,再长的多半是正文自己用了方括号,
而把一整句话当成签名会让前缀匹配变得不可预测。
"""

_MATCHER = re.compile(PATTERN)


def signature_of(body: str | None) -> str | None:
    """抠出正文开头的签名。没有就返回 `None`,**不猜**。

    拿不到签名的短信走不了 `sms_signature` 那条规则 —— 那是对的:
    宁可不放行,也不要用一个猜出来的标识符去匹配白名单。
    """
    if not body:
        return None
    found = _MATCHER.match(body)
    return found.group(1).strip() if found else None
