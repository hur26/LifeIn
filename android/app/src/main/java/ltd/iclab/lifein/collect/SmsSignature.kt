package ltd.iclab.lifein.collect

/**
 * 短信签名 —— 白名单识别银行的那个标识符([ADR-034](../../../../../../../docs/04-tech-decisions.md))。
 *
 * 国内的商业短信在正文开头带一个 `【机构名】`。**它由发信方写进内容**,
 * 所以不受两件事影响,而那两件事正是按号码匹配失效的原因:
 *
 * - 厂商把发件号码换成显示名(通知标题变成"招商银行")
 * - 银行走 SP 网关下发(真实号码 `10693495555`,`95555` 是**子串不是前缀**)
 *
 * 2026-09-11 的三条真实短信里,签名是唯一三条都指向正确机构的信号:
 *
 *     标题='招商银行'        签名='招商银行'
 *     标题='游戏中心'        签名='游戏中心'
 *     标题='10693495555'    签名='招商银行'
 *
 * **这份提取和服务端的 `lifein/sources/sms_signature.py` 各写各的。**
 * 理由和验证码那两份一样([铁律 11](../../../../../../../AGENTS.md)):
 * 两端各自从自己手里那份正文里抠一次,才是两道独立的过滤。
 * 把算好的签名当成字段传上去,服务端那道就退化成"信任设备算的"。
 *
 * **只认开头,不认结尾。** 有些营销短信把签名放在末尾,但手上的真实样本
 * 三条都在开头 —— 见到结尾的那天再扩,不要现在就为没见过的形状写代码。
 */
object SmsSignature {

    /**
     * 正文开头的 `【…】`。中英文方括号都认 —— 有些网关会转成 ASCII 的。
     *
     * 长度上限 20:签名是机构名,再长的多半是正文自己用了方括号,
     * 而把一整句话当成签名会让前缀匹配变得不可预测。
     */
    private val PATTERN = Regex("""^\s*[【\[]([^】\]]{1,20})[】\]]""")

    /**
     * 抠出正文开头的签名。没有就返回 `null`,**不猜**。
     *
     * 拿不到签名的短信走不了 `sms_signature` 那条规则 —— 那是对的:
     * 宁可不放行,也不要用一个猜出来的标识符去匹配白名单。
     */
    fun of(body: String?): String? {
        if (body.isNullOrBlank()) return null
        return PATTERN.find(body)?.groupValues?.get(1)?.trim()?.ifBlank { null }
    }
}
